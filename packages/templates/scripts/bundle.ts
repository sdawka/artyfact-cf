// Collects every template and rule-pack file into src/generated/files.ts so the package works
// without a filesystem (Workers, browser). Run via `npm run build -w @artyfact/templates`.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const roots = ["system", "thing", "rule-packs"];
const exts = [".yaml", ".dl"];

function walk(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : [p];
    });
}

const files = roots
  .flatMap((r) => walk(join(root, r)))
  .filter((p) => exts.some((e) => p.endsWith(e)))
  .map((p) => relative(root, p).split("\\").join("/"))
  .sort();

const body = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(root, f), "utf8"))},`).join("\n");
const out = `// GENERATED by scripts/bundle.ts. Do not edit; run \`npm run build -w @artyfact/templates\`.\nexport const files: Record<string, string> = {\n${body}\n};\n`;
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/files.ts"), out);
console.log(`bundled ${files.length} files`);
